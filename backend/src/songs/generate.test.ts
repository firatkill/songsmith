import { describe, expect, it } from 'vitest';
import type { CatalogueModel, SongJobRow } from '@songsmith/schemas';
import { capabilities } from '../providers/mock/music.js';
import { createMusicA } from '../providers/mock/music-a.js';
import { mockRuntime } from '../providers/mock/latency.js';
import { readMp3Tags, tagMp3 } from '../media/tags.js';
import { pickModel } from './generate.js';

const model = (id: string, extra: Partial<CatalogueModel> = {}) =>
  ({
    id,
    displayName: id,
    qualityRank: id === 'a' ? 20 : 10,
    capabilities: capabilities('b'),
    prices: { generate: 10 },
    languages: { en: 'verified' },
    available: true,
    ...extra,
  }) satisfies CatalogueModel;
const job = (kind: 'auto' | 'manual'): SongJobRow => ({
  id: '00000000-0000-4000-8000-000000000001',
  user_id: '00000000-0000-4000-8000-000000000002',
  operation: 'generate',
  status: 'queued',
  song_id: null,
  model_id: 'a',
  route_reason: { kind },
  reservation_id: null,
  error_code: null,
  stage_detail: null,
  steps: {
    request: {
      title: 't',
      description: 'd',
      lyrics: '',
      language: 'en',
      instrumental: false,
      durationSec: 30,
    },
  },
});

describe('pickModel (FR-29)', () => {
  it('keeps the routed model while it is eligible', () => {
    expect(
      pickModel({
        job: job('auto'),
        models: [model('a'), model('b')],
        reserved: 10,
      }),
    ).toEqual({ modelId: 'a' });
  });
  it('Auto falls back only to a model priced at most the hold', () => {
    const models = [model('a', { available: false }), model('b')];
    expect(pickModel({ job: job('auto'), models, reserved: 10 })).toEqual({
      modelId: 'b',
      fallbackFrom: 'a',
    });
    expect(
      pickModel({
        job: job('auto'),
        models: [
          model('a', { available: false }),
          model('b', { prices: { generate: 11 } }),
        ],
        reserved: 10,
      }),
    ).toEqual({ error: 'NO_ELIGIBLE_MODEL' });
  });
  it('a manual choice never falls back', () => {
    expect(
      pickModel({
        job: job('manual'),
        models: [model('a', { available: false }), model('b')],
        reserved: 10,
      }),
    ).toEqual({ error: 'MODEL_NOT_ELIGIBLE' });
  });
});

describe('ID3 tags (CMP-09)', () => {
  it('marks real mock MP3 audio as AI-generated by the model', async () => {
    const result = await createMusicA(
      mockRuntime({
        PROVIDER_MODE: 'mock',
        MOCK_LATENCY_MS: 0,
        MOCK_FAILURE_RATE: 0,
      }),
    ).generate(
      { description: 'x', language: 'en', durationSec: 2, format: 'mp3' },
      {
        jobId: 'j',
        userId: 'u',
        correlationId: 'c',
        signal: AbortSignal.timeout(5000),
      },
    );
    if (result.kind !== 'done' || !(result.output.bytes instanceof Uint8Array))
      throw new Error('expected audio');
    const tags = readMp3Tags(
      tagMp3(result.output.bytes, { title: 'T', artist: 'A', modelId: 'm' }),
    );
    expect(tags).toMatchObject({
      title: 'T',
      artist: 'A',
      comment: { text: 'AI-generated with m' },
    });
    expect(tags.userDefinedText).toEqual(
      expect.arrayContaining([{ description: 'ai_generated', value: 'true' }]),
    );
  });
});
